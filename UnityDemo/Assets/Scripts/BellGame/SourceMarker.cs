// SourceMarker.cs
// 「これは検証用の目印であって、世界の持ち物ではない」という名札。
//
// ★なぜ要るか
//   WorldSet.HideMarkers は「音源の見た目を隠す」処理で、狙いは
//   **位置を目で教えないこと**（音だけで探す）。
//   ところが判定が「IrConvolver を持っているか」だったので、
//   音を出す物は**全部**目印扱いになり、本番のベルのモデルまで消えていた。
//
//   目印か本物かは、見た目からは決められない。だから目印の側に名札を付ける。
//   名札が無い物は本物とみなす ── 消し忘れより、消しすぎのほうが困る
//  （在るはずの物が無いと、何が起きているのか分からなくなる）。
//
// ★「音だけで探す」は守る。
//   それは**位置を教える印を出さない**という意味であって、
//   其処に在る物を消すことではない。見つけたベルは見えてよい。
using UnityEngine;

namespace BellGame
{
    /// 検証用に置いた音源の目印。付いている物だけが HideMarkers の対象になる。
    [DisallowMultipleComponent]
    public sealed class SourceMarker : MonoBehaviour { }
}

// SourceTierTag.cs
// この音源をどの段で解くか。**音源そのものに貼る札**。
//
// ★段はオーサリングです（サウンドレーンの言葉のまま）。
//   エンジンは 3 つの解き方を持っていますが、**既定は全部「厳密」**で、
//   こちらが音源ごとに決めるまで 1% も動きません。
//
// ★なぜ音源に貼るか
//   段は「その音が体験の何を担うか」で決まります。距離でも音量でもありません。
//   ベルは 100m 先でも厳密であるべきだし、足元の草擦れは 1m でも簡易でよい。
//   **担っている役割は音源自身の性質**なので、音源が持つのが筋です。
//   一覧表を別に持つと、音源を増やしたときに表の更新が漏れます。
//
// ★段が何を落とすか（サウンドレーンの実測・実機 45% の内訳より）
//     直接音                     0.12 % / 本
//     早期反射                  +0.32 % / 本
//     遮蔽された音源の回折 HRTF  2.32 % / 本   ← 残りの半分以上
//
//   **簡易が落とすのはこの 2.32% です。**代わりに失うもの:
//     ・回り込みの**方向**が出ない（壁の向こうの音が壁の中から鳴る）
//     ・近接感が落ちる（早期反射なし）
//
// ⚠ ここはコンセプトの芯に触ります。
//   「周辺環境の変化を音で伝える」の、伝える側を削る操作です。
//   **費用で決めず、耳で決めること。**迷ったら厳密のままにしてください。
using UnityEngine;

namespace BellGame
{
    [DisallowMultipleComponent]
    public sealed class SourceTierTag : MonoBehaviour
    {
        // ★AcousticScene.SourceTier と同じ並び。
        //   別の enum を作るのは避けたいところですが、
        //   BellGame から AcousticFlow の enum を直に露出させると
        //   インスペクタが system 側の型に依存します。並びは固定なので
        //   SourceTierApplier が 1 箇所で写します。
        public enum Tier
        {
            Exact = 0,      // 厳密 ── 体験の芯。扉の奥の音、探しているベル
            Simple = 1,     // 簡易 ── 背景の環境音、遠景の小物
            Virtual = 2,    // バーチャル ── 半径の外では解かない
        }

        [Header("段")]
        [Tooltip("既定は厳密。迷ったら変えないこと。")]
        public Tier tier = Tier.Exact;

        [Header("バーチャルの半径")]
        // ★0 なら自動バーチャルなし。
        //   響く部屋では、自由音場の計算より遠くまで聞こえます ──
        //   半径を小さく取りすぎると**聞こえるはずの音が消えます**。
        //   小さくするより大きめに取って、足りなければ縮めること。
        [Tooltip("この距離より遠いと解かない（0 = 自動バーチャルなし）。")]
        [Range(0f, 200f)] public float audibleRadius = 0f;

        [Header("診断（読み取り専用）")]
        [Tooltip("エンジンがいま実際に使っている段。指定と違うならエンジンが落としている。")]
        public string effective = "—";
    }
}
